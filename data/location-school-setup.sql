-- Run after data/field-access-setup.sql as the project owner.
-- Location assignments start empty; manage them from the authenticated admin dashboard.
begin;

create table if not exists public.school_partners (
  id bigint generated by default as identity primary key,
  name text not null unique,
  logo_path text
);

insert into public.school_partners (id, name, logo_path) values
  (1, 'St Hilda''s Collegiate', 'assets/shcslogo.jpg'),
  (2, 'Trinity College', 'assets/trinitylogo.png'),
  (3, 'Logan Park High School', 'assets/lphslogo.png'),
  (4, 'Bayfield High School', 'assets/bayfieldlogo.png'),
  (5, 'Columba College', 'assets/columbalogo.png')
on conflict (name) do update set logo_path = excluded.logo_path;
select setval(
  pg_get_serial_sequence('public.school_partners', 'id'),
  greatest(coalesce((select max(id) from public.school_partners), 1), 1),
  true
);

create table if not exists public.location_school_assignments (
  location_id bigint primary key references public.locations(id) on delete cascade,
  school_id bigint not null references public.school_partners(id) on delete restrict,
  updated_at timestamptz not null default now(),
  updated_by uuid not null references auth.users(id)
);

create table if not exists public.location_school_history (
  id bigint generated always as identity primary key,
  location_id bigint not null references public.locations(id) on delete cascade,
  previous_school_id bigint references public.school_partners(id) on delete set null,
  new_school_id bigint references public.school_partners(id) on delete set null,
  changed_at timestamptz not null default now(),
  changed_by uuid not null references auth.users(id)
);

alter table public.school_partners enable row level security;
alter table public.location_school_assignments enable row level security;
alter table public.location_school_history enable row level security;
revoke all on public.school_partners, public.location_school_assignments from public, anon, authenticated;
revoke all on public.location_school_history from public, anon, authenticated;

create or replace function public.location_school_list()
returns table(location_id bigint, location_name text, school_id bigint, school_name text, logo_path text)
language sql stable security definer set search_path = pg_catalog, public
as $$
  select l.id, coalesce(l.location, l.id::text), s.id, s.name, s.logo_path
  from public.locations l
  left join public.location_school_assignments a on a.location_id = l.id
  left join public.school_partners s on s.id = a.school_id
  order by coalesce(l.location, l.id::text);
$$;

create or replace function public.school_partner_list()
returns table(school_id bigint, school_name text, logo_path text)
language sql stable security definer set search_path = pg_catalog, public
as $$
  select id, name, logo_path from public.school_partners order by name;
$$;

create or replace function public.location_school_history_list()
returns table(location_name text, previous_school_name text, new_school_name text, changed_at timestamptz)
language plpgsql stable security definer set search_path = pg_catalog, public
as $$
begin
  if not exists (select 1 from public.field_access_admins where user_id = auth.uid()) then
    raise exception 'Not authorized to view location school history';
  end if;
  return query
    select coalesce(l.location, l.id::text),
      previous_school.name, next_school.name, h.changed_at
    from public.location_school_history h
    join public.locations l on l.id = h.location_id
    left join public.school_partners previous_school on previous_school.id = h.previous_school_id
    left join public.school_partners next_school on next_school.id = h.new_school_id
    order by h.changed_at desc;
end;
$$;

create or replace function public.location_school_change(p_location_id bigint, p_school_id bigint)
returns void
language plpgsql security definer set search_path = pg_catalog, public
as $$
begin
  if not exists (select 1 from public.field_access_admins where user_id = auth.uid()) then
    raise exception 'Not authorized to manage location schools';
  end if;
  if not exists (select 1 from public.locations where id = p_location_id) then
    raise exception 'Unknown location';
  end if;
  if p_school_id is not distinct from (
    select school_id from public.location_school_assignments where location_id = p_location_id
  ) then
    return;
  end if;
  insert into public.location_school_history(location_id, previous_school_id, new_school_id, changed_by)
    select p_location_id, school_id, p_school_id, auth.uid()
    from public.location_school_assignments where location_id = p_location_id;
  if not found and p_school_id is not null then
    insert into public.location_school_history(location_id, new_school_id, changed_by)
      values (p_location_id, p_school_id, auth.uid());
  end if;
  if p_school_id is null then
    delete from public.location_school_assignments where location_id = p_location_id;
  else
    if not exists (select 1 from public.school_partners where id = p_school_id) then
      raise exception 'Unknown school';
    end if;
    insert into public.location_school_assignments(location_id, school_id, updated_by)
      values (p_location_id, p_school_id, auth.uid())
      on conflict (location_id) do update
        set school_id = excluded.school_id, updated_at = now(), updated_by = excluded.updated_by;
  end if;
end;
$$;

grant execute on function public.location_school_list() to anon, authenticated;
grant execute on function public.school_partner_list() to authenticated;
grant execute on function public.location_school_history_list() to authenticated;
grant execute on function public.location_school_change(bigint, bigint) to authenticated;
notify pgrst, 'reload schema';
commit;
